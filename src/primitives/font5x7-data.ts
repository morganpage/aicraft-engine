/**
 * The default 5×7 bitmap font — 95 printable ASCII glyphs (0x20–0x7E),
 * column-major hex bytes (one byte per column, bit 0 = top row).
 *
 * Source: Pascal Stang's `font5x7.h` from the GLCD library
 * (https://andygock.github.io/glcd-documentation/font5x7_8h_source.html),
 * cited in `docs/research/bitmap-font.md`. This is the most widely deployed
 * 5×7 font in embedded systems — byte-for-byte identical to the HD44780 LCD
 * controller ROM shipped in 1987. MIT-licensed; attribution preserved below.
 *
 * Encoding: each glyph is 5 bytes. The flat array is indexed by
 * `(charCode - 0x20) * 5`. To read a glyph visually, decode each byte LSB-first
 * over 7 rows (bit 0 = top row, bit 6 = bottom row, bit 7 unused). For example
 * `'A'` = `[0x7E, 0x11, 0x11, 0x11, 0x7E]` — grep-friendly.
 *
 * 95 glyphs × 5 bytes = 475 bytes total.
 *
 * Divergence from upstream Stang: the 0x7E glyph (ASCII tilde `~`) is drawn
 * in Stang's source as a right arrow (`->`). That is faithful to the upstream
 * dataset but renders incorrectly wherever a real tilde is expected (e.g.
 * version strings like `v1.0~beta`). We hand-author a real tilde wave here —
 * see the inline comment at the 0x7E row for the chosen bytes and rationale.
 * This is the ONLY byte that diverges from upstream Stang.
 *
 * @module
 */

