/**
 * charCode → glyph-bytes view of {@link FONT_5X7_DATA}, keyed by ASCII code
 * (0x20–0x7E). Built once at module load. Used by {@link DEFAULT_FONT}.
 */
export const FONT_5X7_GLYPHS: ReadonlyMap<number, GlyphData> = (() => {
  const map = new Map<number, GlyphData>();
  for (let code = FONT_5X7_FIRST_CHAR; code <= FONT_5X7_LAST_CHAR; code++) {
    const offset = (code - FONT_5X7_FIRST_CHAR) * FONT_5X7_CELL_WIDTH;
    map.set(code, FONT_5X7_DATA.slice(offset, offset + FONT_5X7_CELL_WIDTH));
  }
  return map;
})();
