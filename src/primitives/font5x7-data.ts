/** Cell width of the 5×7 font (columns per glyph = bytes per glyph). */
export const FONT_5X7_CELL_WIDTH = 5;

/** Cell height of the 5×7 font (rows per glyph = bits used per column byte). */
export const FONT_5X7_CELL_HEIGHT = 7;

/** First charCode covered by the dataset (space). */
export const FONT_5X7_FIRST_CHAR = 0x20;

/** Last charCode covered by the dataset. */
export const FONT_5X7_LAST_CHAR = 0x7e;

